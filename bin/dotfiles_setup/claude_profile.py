"""Removes the per-session Claude Code profile files that earlier installs generated; presets now merge into settings.json."""
from __future__ import annotations

from pathlib import Path

from dotfiles_setup.tooling import Tooling, dry_run_all

SCRIPT_MARKER = "Generated by dotfiles-setup (claude_profile.py)"
ALIASES_MARKER = "Claude Code profiles (generated by dotfiles-setup"
GENERATED_PROFILES = ("claude_work.json", "claude_personal.json", "claude_homelab.json")


def _generated_files(home: Path) -> tuple[tuple[Path, str], ...]:
    return (
        (home / "bin/claude", SCRIPT_MARKER),
        (home / ".zshrc.profile", ALIASES_MARKER),
        (home / ".config/environment.d/zz-claude-profile.conf", SCRIPT_MARKER),
    )


def _remove_if_generated(path: Path, marker: str) -> bool:
    if not path.is_file() or marker not in path.read_text(encoding="utf-8", errors="replace"):
        return False
    path.unlink()
    return True


def _remove_profiles(profile_dir: Path) -> list[Path]:
    removed = [profile_dir / name for name in GENERATED_PROFILES if (profile_dir / name).is_file()]
    for profile in removed:
        profile.unlink()
    if profile_dir.is_dir() and not profile_dir.is_symlink() and not any(profile_dir.iterdir()):
        profile_dir.rmdir()
    return removed


def retire_claude_profile(t: Tooling) -> None:
    t.logger.step("Step 7b: Removing retired Claude Code profile files...")
    home = t.home
    profile_dir = home / ".config/dotfiles/claude-profiles"
    if dry_run_all(t, f"Would remove the generated claude wrapper, aliases and profiles under {profile_dir}"):
        return
    removed = [path for path, marker in _generated_files(home) if _remove_if_generated(path, marker)]
    removed += _remove_profiles(profile_dir)
    for path in removed:
        t.logger.info(f"Removed {path}.")
    if (home / ".zshrc.profile").exists():
        t.logger.warn(f"{home / '.zshrc.profile'} is no longer loaded by .zshrc; move its customizations to ~/.zshrc.secret.")
    if (home / ".claude-burst").exists():
        t.logger.warn(f"{home / '.claude-burst'} is no longer used; delete it once you no longer need its credentials.")
