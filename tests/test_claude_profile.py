from types import SimpleNamespace

from dotfiles_setup import claude_profile as cp
from dotfiles_setup import tools
from dotfiles_setup.log import Logger

WRAPPER = "#!/bin/sh\n# Generated by dotfiles-setup (claude_profile.py) — do not edit.\nexec claude\n"
ALIASES = "# --- Claude Code profiles (generated by dotfiles-setup, do not edit) ---\nalias claude='x'\n"
ENV_FILE = "# Generated by dotfiles-setup (claude_profile.py) — do not edit.\nPATH=/h/bin:${PATH}\n"


def make(tmp_path, dry_run=False):
    home = tmp_path / "home"
    home.mkdir()
    t = tools.Tooling(Logger(dry_run=dry_run, verbosity=1), home, run=lambda *a, **k: SimpleNamespace(returncode=0))
    return t, home


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    return path


def generated(home):
    return [
        write(home / "bin/claude", WRAPPER),
        write(home / ".zshrc.profile", ALIASES),
        write(home / ".config/environment.d/zz-claude-profile.conf", ENV_FILE),
    ]


def test_the_generated_wrapper_aliases_and_session_path_file_are_removed(tmp_path):
    t, home = make(tmp_path)
    files = generated(home)
    cp.retire_claude_profile(t)
    assert not any(f.exists() for f in files)


def test_the_generated_profile_files_and_their_empty_directory_are_removed(tmp_path):
    t, home = make(tmp_path)
    profiles = home / ".config/dotfiles/claude-profiles"
    for name in ("work", "homelab"):
        write(profiles / f"claude_{name}.json", "{}")
    cp.retire_claude_profile(t)
    assert not profiles.exists()


def test_a_profile_directory_holding_other_files_is_kept(tmp_path):
    t, home = make(tmp_path)
    profiles = home / ".config/dotfiles/claude-profiles"
    write(profiles / "claude_work.json", "{}")
    keep = [write(profiles / "notes.txt", "mine"), write(profiles / "claude_custom.json", "{}")]
    cp.retire_claude_profile(t)
    assert all(path.exists() for path in keep)
    assert not (profiles / "claude_work.json").exists()


def test_a_file_the_user_wrote_at_a_generated_path_is_left_alone(tmp_path):
    t, home = make(tmp_path)
    wrapper = write(home / "bin/claude", "#!/bin/sh\nexec /opt/claude \"$@\"\n")
    aliases = write(home / ".zshrc.profile", "alias ll='ls -l'\n")
    cp.retire_claude_profile(t)
    assert wrapper.exists()
    assert aliases.exists()


def test_a_kept_zshrc_profile_warns_that_it_is_no_longer_loaded(tmp_path, capsys):
    t, home = make(tmp_path)
    write(home / ".zshrc.profile", "alias ll='ls -l'\n")
    cp.retire_claude_profile(t)
    assert ".zshrc.profile is no longer loaded" in capsys.readouterr().out


def test_a_dry_run_removes_nothing(tmp_path):
    t, home = make(tmp_path, dry_run=True)
    files = generated(home)
    write(home / ".config/dotfiles/claude-profiles/claude_work.json", "{}")
    cp.retire_claude_profile(t)
    assert all(f.exists() for f in files)
    assert (home / ".config/dotfiles/claude-profiles/claude_work.json").exists()


def test_a_home_without_any_generated_files_is_a_no_op(tmp_path):
    t, home = make(tmp_path)
    cp.retire_claude_profile(t)
    assert list(home.iterdir()) == []


def test_the_old_burst_config_dir_is_never_deleted(tmp_path):
    t, home = make(tmp_path)
    credentials = write(home / ".claude-burst/.credentials.json", "{}")
    cp.retire_claude_profile(t)
    assert credentials.exists()
